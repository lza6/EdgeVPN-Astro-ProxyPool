#!/usr/bin/env python3
"""精确 DEX 指令解码: 正确跳过操作数, 提取 const-string 与 invoke 目标."""

# 每条 opcode 的码元数 (16-bit units)
LEN = {}
def _set(ops, n):
    for o in ops: LEN[o] = n
_set([0x00,0x01,0x04,0x07,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,0x10,0x11,0x12,0x1d,0x1e,0x21,0x27,0x28],1)
_set([0x02,0x05,0x08,0x13,0x15,0x16,0x19,0x1a,0x1c,0x1f,0x20,0x22,0x23,0x29,0xfe,0xff],2)
_set([0x03,0x06,0x09,0x14,0x17,0x1b,0x24,0x25,0x26,0x2a,0x2b,0x2c,0x6e,0x6f,0x70,0x71,0x72,0x74,0x75,0x76,0x77,0x78,0xfc,0xfd],3)
_set([0xfa,0xfb],4)
_set([0x18],5)
_set(list(range(0x2d,0x32)),2)      # cmp*
_set(list(range(0x32,0x38)),2)      # if-*
_set(list(range(0x38,0x3e)),2)      # if-*z
_set(list(range(0x44,0x52)),2)      # aget/aput
_set(list(range(0x52,0x60)),2)      # iget/iput
_set(list(range(0x60,0x6e)),2)      # sget/sput
_set(list(range(0x7b,0x90)),1)      # unop
_set(list(range(0x90,0xb0)),2)      # binop
_set(list(range(0xb0,0xd8)),2)      # binop/lit16 + lit8
_set([0x73,0x79,0x7a],1)

def scan(insns):
    """返回 [(offset, kind, index)] kind in {'str','invoke'}"""
    out = []
    i = 0
    n = len(insns)
    while i < n:
        op = insns[i] & 0xFF
        if op == 0x1A and i + 1 < n:
            out.append((i, 'str', insns[i+1]))
        elif op == 0x1B and i + 2 < n:
            out.append((i, 'str', insns[i+1] | (insns[i+2] << 16)))
        elif 0x6E <= op <= 0x72 or 0x74 <= op <= 0x78:
            if i + 1 < n:
                out.append((i, 'invoke', insns[i+1]))
        i += LEN.get(op, 1)
    return out
